"""Tests for the Rust lexing helpers."""

import unittest

from support import rust_source

import rust_uses


class SourceTest(unittest.TestCase):
    def test_strip_code_blanks_comments_and_strings(self):
        code = rust_source.strip_code(['let s = "{"; // }', "/* { */ let x = 1;"])
        self.assertNotIn("{", code[0])
        self.assertNotIn("}", code[0])
        self.assertEqual(code[1].strip(), "let x = 1;")

    def test_comments_are_kept_apart_from_strings(self):
        src = rust_source.parse('let s = "// TODO"; // real\n/* a\nb */ let c = \'"\';\nlet r = r#"/* x */"#;')
        self.assertEqual(src.comments[:3], [" real", " a", "b "])
        self.assertEqual(src.comments[3], "")
        self.assertNotIn('"', src.code[2].replace('""', "").replace("''", ""))

    def test_multiline_string_with_escaped_quote(self):
        src = rust_source.parse('let s = "a \\"{\nb {";\nfn f() {}')
        self.assertEqual(src.depth, [0, 0, 0])

    def test_test_span_covers_the_test_module(self):
        src = rust_source.parse("//! doc\nfn a() {}\n#[cfg(test)]\nmod tests {\n    fn t() {}\n}\n")
        self.assertEqual(src.test_span, (2, 6))
        self.assertEqual(src.production_lines(), 3)

    def test_test_span_on_one_line(self):
        src = rust_source.parse("//! doc\nfn a() {}\n#[cfg(test)] mod tests {\n    fn t() {}\n}\n")
        self.assertEqual(src.test_span, (2, 5))

    def test_generated_marker_only_on_line_one(self):
        self.assertTrue(rust_source.parse("// @generated by build.rs\nfn a() {}").is_generated())
        self.assertFalse(rust_source.parse("//! doc\n// @generated\nfn a() {}").is_generated())
        self.assertFalse(rust_source.parse("// Do not edit: this is hand-written\nfn a() {}").is_generated())


class UsesTest(unittest.TestCase):
    def test_expand_groups(self):
        self.assertEqual(rust_uses.expand("std::{fs, io::{self, Read as R}, thread::sleep}"), ["std::fs", "std::io", "std::io::Read", "std::thread::sleep"])

    def test_declarations_span_lines(self):
        decls = rust_uses.use_declarations(["use std::{", "    fs,", "};", "fn f() {}"])
        self.assertEqual([(d.first, d.last) for d in decls], [(0, 2)])
        self.assertEqual(rust_uses.expand(decls[0].tree), ["std::fs"])


if __name__ == "__main__":
    unittest.main()
