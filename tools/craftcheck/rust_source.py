"""Just enough Rust lexing for file-level rules: code without literals and
comments, brace depth per line, the test module's span, top-level items."""

import re
from dataclasses import dataclass

STRING = re.compile(r'b?"(?:\\.|[^"\\])*"|b?\'(?:\\.|[^\'\\])\'')
TEST_CFG = re.compile(r"^\s*#\[cfg\((test|all\(test\b|any\(test\b)")
MOD_BLOCK = re.compile(r"^\s*(pub(\([^)]*\))?\s+)?mod\s+\w+\s*\{")
ITEM = re.compile(
    r"^(?P<vis>pub(\([^)]*\))?\s+)?(?:unsafe\s+|const\s+|async\s+|extern\s+\"[^\"]*\"\s+)*"
    r"(?P<kind>fn|struct|enum|trait|impl|type|const|static|union|mod|macro_rules!)\b\s*(?P<name>\w*)"
)
GENERATED = re.compile(r"^\s*//.*(@generated|Generated by|Do not edit)", re.I)


@dataclass
class Item:
    line: int  # 1-based
    kind: str
    name: str
    public: bool


@dataclass
class Source:
    lines: list
    code: list  # each line with comments and literals blanked out
    depth: list  # brace depth at the start of each line
    test_span: tuple  # (start, end) 0-based, end exclusive; (n, n) if none

    def production_lines(self) -> int:
        start, end = self.test_span
        return len(self.lines) - (end - start)

    def is_generated(self) -> bool:
        return any(GENERATED.match(line) for line in self.lines[:3])


def strip_code(lines: list) -> list:
    """Blank out comments and string/char literals, keeping line count."""
    out, in_block, in_raw = [], 0, None
    for line in lines:
        buf, i = [], 0
        while i < len(line):
            if in_raw:
                end = line.find(in_raw, i)
                if end < 0:
                    i = len(line)
                    continue
                i, in_raw = end + len(in_raw), None
                buf.append('""')
                continue
            if in_block:
                if line.startswith("*/", i):
                    in_block, i = in_block - 1, i + 2
                elif line.startswith("/*", i):
                    in_block, i = in_block + 1, i + 2
                else:
                    i += 1
                continue
            if line.startswith("//", i):
                break
            if line.startswith("/*", i):
                in_block, i = 1, i + 2
                continue
            raw = re.match(r'b?r(#*)"', line[i:])
            if raw and (i == 0 or not (line[i - 1].isalnum() or line[i - 1] == "_")):
                in_raw, i = '"' + raw.group(1), i + raw.end()
                continue
            lit = STRING.match(line, i)
            if lit:
                buf.append('""')
                i = lit.end()
                continue
            if line[i] == '"':  # a string that continues on the next line
                in_raw, i = '"', i + 1
                continue
            buf.append(line[i])
            i += 1
        out.append("".join(buf))
    return out


def parse(text: str) -> Source:
    lines = text.split("\n")
    code = strip_code(lines)
    depth, d = [], 0
    for c in code:
        depth.append(d)
        d += c.count("{") - c.count("}")
    return Source(lines, code, depth, _test_span(code, depth))


def _test_span(code: list, depth: list) -> tuple:
    n = len(code)
    for i, c in enumerate(code):
        if depth[i] != 0 or not TEST_CFG.match(c):
            continue
        k = i + 1
        while k < n and code[k].strip().startswith("#["):
            k += 1
        if k < n and MOD_BLOCK.match(code[k]):
            end = k + 1
            while end < n and depth[end] > 0:
                end += 1
            return (i, end)
    return (n, n)


def top_level_items(src: Source) -> list:
    """Items at brace depth 0, outside the test module."""
    start, end = src.test_span
    items = []
    for i, c in enumerate(src.code):
        if src.depth[i] != 0 or start <= i < end:
            continue
        m = ITEM.match(c)
        if m:
            items.append(Item(i + 1, m.group("kind"), m.group("name"), bool(m.group("vis"))))
    return items


def module_doc_lines(src: Source) -> int:
    """Number of leading `//!` lines (after blank lines)."""
    count, seen = 0, False
    for line in src.lines:
        s = line.strip()
        if s.startswith("//!"):
            count, seen = count + 1, True
        elif s.startswith("#![") or (not s and not seen):
            continue
        else:
            break
    return count


def camel(snake: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in snake.split("_"))
